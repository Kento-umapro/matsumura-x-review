def kill_last_hisyo(body):
    """末尾が秘書の一行なら落とす"""
    lines = [l for l in body.split("\n")]
    while lines and not lines[-1].strip():
        lines.pop()
    if lines and lines[-1].startswith("秘書「"):
        lines.pop()
        while lines and not lines[-1].strip():
            lines.pop()
    return "\n".join(lines)

def is_shodaku(body):
    """末尾の秘書行が短い決意表明かどうか（未判定分への横展開用）"""
    import re
    lines = [l for l in body.split("\n") if l.strip()]
    if not lines or not lines[-1].startswith("秘書「"):
        return False
    m = re.match(r'^秘書「(.+?)」$', lines[-1])
    if not m:
        return False
    t = m.group(1)
    return len(t) <= 10 and re.search(r'(ます|です)$', t) is not None
