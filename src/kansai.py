"""コテコテの関西弁だけを標準語に寄せる（2026-09-07 松村さん指示）

「俺は〜やない とは言わへん。〜じゃない と言う。コテコテの関西弁はやめてほしい」

薄めるのは下の8語だけ。「やろ」「〜へん」「あかん」「ええ」は
関西のニュアンスとして残す（全部消すとBOSSの人格が消えるため）。
"""

RULES = [
    ('せやねん',   'そうや'),
    ('せやから',   'だから'),
    ('せやろ',     'そうやろ'),
    ('せやな',     'そうやな'),
    ('せや。',     'そうや。'),
    ('せや、',     'そうや、'),
    ('せや」',     'そうや」'),
    ('やねん',     'や'),
    ('もんちゃう', 'もんじゃない'),
    ('ちゃう',     '違う'),
    ('ほんま',     '本当'),
    ('なんぼ',     'いくら'),
    ('やない',     'じゃない'),
]


def soften(body):
    """薄めた本文と、変えたかどうかを返す。"""
    out = body
    for a, b in RULES:
        out = out.replace(a, b)
    return out, (out != body)
